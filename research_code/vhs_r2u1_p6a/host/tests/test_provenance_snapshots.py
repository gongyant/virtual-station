"""
tests/test_provenance_snapshots.py  --  Codex P1-02 (fail-closed provenance)

Pure SYNTHETIC: six tiny CSVs are generated by test_syrdarya_synthetic.build
inside W/tests/_fixtures/prov_case and every tamper case is applied to a
copy there. The teacher's files are never opened by this suite except
test M01, which only hashes the frozen manifest JSON in W/manifest.
"""
import builtins
import hashlib
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
sys.path.insert(0, APP)
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True

from _harness import Suite  # noqa: E402
import provenance_snapshot as PS  # noqa: E402
import syrdarya_adapter as SA  # noqa: E402
from test_syrdarya_synthetic import build  # noqa: E402

FIX = os.path.join(HERE, "_fixtures", "prov_case")
T = Suite("test_provenance_snapshots")
NAMES = list(SA.FILES.values())


def sha(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def fresh(name):
    d = os.path.join(FIX, name)
    if os.path.isdir(d):
        shutil.rmtree(d)
    os.makedirs(d)
    build(d)
    return d


def manifest(d, fname="pin.json", mutate=None):
    files = [{"file": n, "bytes": os.path.getsize(os.path.join(d, n)),
              "sha256": sha(os.path.join(d, n))} for n in NAMES]
    doc = {"files": files}
    if mutate:
        mutate(doc)
    p = os.path.join(d, fname)
    with open(p, "w", encoding="utf-8") as f:
        json.dump(doc, f)
    return p


def store(d, mp, msha=None):
    return SA.SyrDaryaStore(d, pinned_manifest=mp,
                            expected_manifest_sha256=msha)


def main():
    if os.path.isdir(FIX):
        shutil.rmtree(FIX)
    d = fresh("base")
    mp = manifest(d)
    s = store(d, mp, sha(mp))
    T.check("P01", "complete pin + frozen manifest sha -> OK",
            s.status == "OK" and s.snapshot is not None, s.status)
    inf = s.snapshot_public()
    T.check("P02", "snapshot exposes snapshot_id / loaded_at / policy",
            inf["snapshot_id"].startswith("syr-snap-") and inf["loaded_at"]
            and inf["policy"] == "IMMUTABLE_LOAD_SNAPSHOT", inf)
    s_b = store(d, mp, sha(mp))
    T.check("P03", "snapshot_id deterministic for identical pinned bytes",
            s_b.snapshot.snapshot_id == s.snapshot.snapshot_id)
    T.check("P04", "semantics say verified-at-load, not 'disk unchanged now'",
            "不等于" in inf["semantics"] and
            inf["disk_currently_unchanged"].startswith("NOT_ASSERTED"))

    # ---- manifest defects --------------------------------------------
    s2 = store(d, os.path.join(d, "nope.json"))
    T.check("M02", "manifest file missing -> MANIFEST_MISSING, no data",
            s2.status == "MANIFEST_MISSING" and not s2.discharge, s2.status)
    s2 = store(d, None)
    T.check("M03", "no manifest configured -> MANIFEST_MISSING",
            s2.status == "MANIFEST_MISSING")
    cases = [
        ("M04", "manifest lacks one entry",
         lambda doc: doc["files"].pop()),
        ("M05", "manifest has extra entry",
         lambda doc: doc["files"].append({"file": "extra.csv", "bytes": 1,
                                          "sha256": "a" * 64})),
        ("M06", "duplicate entry", lambda doc: doc["files"].append(
            dict(doc["files"][0]))),
        ("M07", "malformed sha256 (63 hex)", lambda doc: doc["files"][0]
         .__setitem__("sha256", "a" * 63)),
        ("M08", "uppercase / non-hex sha256", lambda doc: doc["files"][1]
         .__setitem__("sha256", "G" * 64)),
        ("M09", "bytes missing", lambda doc: doc["files"][2].pop("bytes")),
        ("M10", "entry without file name", lambda doc: doc["files"][3]
         .pop("file")),
        ("M11", "files not a list", lambda doc: doc.__setitem__("files",
                                                                {"a": 1})),
    ]
    for tid, title, mut in cases:
        p = manifest(d, "pin_%s.json" % tid, mut)
        x = store(d, p)
        T.check(tid, title + " -> MANIFEST_INVALID, no data",
                x.status == "MANIFEST_INVALID" and not x.discharge and
                x.snapshot is None and x.refusal, (x.status, x.refusal))
    p = os.path.join(d, "pin_bad.json")
    with open(p, "w", encoding="utf-8") as f:
        f.write("{not json")
    T.check("M12", "unreadable manifest -> MANIFEST_INVALID",
            store(d, p).status == "MANIFEST_INVALID")
    T.check("M13", "valid manifest but not the frozen manifest sha -> "
            "MANIFEST_INVALID", store(d, mp, "b" * 64).status ==
            "MANIFEST_INVALID")

    # ---- source defects (all-or-nothing) -----------------------------
    d3 = fresh("hash")
    mp3 = manifest(d3)
    with open(os.path.join(d3, SA.FILES["kzdam"]), "ab") as f:
        f.write(b"\n")
    x = store(d3, mp3)
    T.check("F01", "one file changed (size) -> SOURCE_CHANGED, whole "
            "dataset refused", x.status == "SOURCE_CHANGED" and
            not x.discharge and not x.met and not x.wb, x.status)
    errs = x.refusal["errors"] if x.refusal else []
    T.check("F02", "refusal names the file and both hashes",
            any(e.get("file") == SA.FILES["kzdam"] and e.get(
                "observed_sha256") and e.get("pinned_sha256") for e in errs),
            errs)
    d4 = fresh("samesize")
    mp4 = manifest(d4)
    fp = os.path.join(d4, SA.FILES["circles"])
    raw = bytearray(open(fp, "rb").read())
    i = raw.rfind(b"1")
    raw[i:i + 1] = b"2"                    # same size, different bytes
    open(fp, "wb").write(bytes(raw))
    T.check("F03", "same-size content change -> SOURCE_CHANGED",
            store(d4, mp4).status == "SOURCE_CHANGED")
    d5 = fresh("missing")
    mp5 = manifest(d5)
    os.remove(os.path.join(d5, SA.FILES["met"] if "met" in SA.FILES else
                           NAMES[-1]))
    x = store(d5, mp5)
    T.check("F04", "one file missing -> SOURCE_MISSING, nothing served",
            x.status == "SOURCE_MISSING" and not x.discharge, x.status)
    before = sha(mp3)
    store(d3, mp3)
    T.check("F05", "refusal never rewrites the pinned manifest",
            sha(mp3) == before)

    # ---- single read: hash and parse the SAME bytes ------------------
    d6 = fresh("single")
    mp6 = manifest(d6)
    opened = []
    real_open = builtins.open

    def spy(file, mode="r", *a, **k):
        try:
            nm = os.path.basename(os.fspath(file))
        except TypeError:
            nm = ""
        if nm in NAMES:
            opened.append((nm, mode))
        return real_open(file, mode, *a, **k)
    builtins.open = spy
    try:
        x = store(d6, mp6)
    finally:
        builtins.open = real_open
    per = {n: sum(1 for o in opened if o[0] == n) for n in NAMES}
    T.check("R01", "each source file opened exactly once during load",
            x.status == "OK" and all(v == 1 for v in per.values()), per)
    T.check("R02", "that single open is binary (bytes hashed = bytes parsed)",
            all("b" in m for _, m in opened), opened)

    # ---- tamper after load: snapshot immutable, recheck reports ------
    q_before = [(o.station_uid, o.year, o.month, o.stat, o.value)
                for o in x.discharge]
    sid = x.snapshot.snapshot_id
    t0 = x.snapshot.loaded_at
    fp = os.path.join(d6, SA.FILES["discharge"])
    raw = bytearray(open(fp, "rb").read())
    raw[-3:-2] = b"9" if raw[-3:-2] != b"9" else b"8"
    open(fp, "wb").write(bytes(raw))
    rc = x.snapshot.recheck()
    T.check("T01", "recheck after tamper -> disk_matches_snapshot False, "
            "file CHANGED", rc["disk_matches_snapshot"] is False and any(
                r["result"] == "CHANGED" and r["file"] ==
                SA.FILES["discharge"] for r in rc["files"]), rc)
    T.check("T02", "recheck does not alter snapshot id / load time / data",
            x.snapshot.snapshot_id == sid and x.snapshot.loaded_at == t0 and
            [(o.station_uid, o.year, o.month, o.stat, o.value)
             for o in x.discharge] == q_before and x.status == "OK")
    T.check("T03", "recheck result carries its own timestamp + effect NONE",
            rc["rechecked_at"] and rc["effect"].startswith("NONE"))
    T.check("T04", "fresh load of tampered copy -> SOURCE_CHANGED",
            store(d6, mp6).status == "SOURCE_CHANGED")
    os.remove(os.path.join(d6, SA.FILES["intakes"]))
    rc2 = x.snapshot.recheck()
    T.check("T05", "recheck reports MISSING file, still no side effect",
            any(r["result"] == "MISSING" for r in rc2["files"]) and
            x.status == "OK" and x.snapshot.snapshot_id == sid)
    d7 = fresh("clean")
    mp7 = manifest(d7)
    y = store(d7, mp7)
    T.check("T06", "recheck on untouched copy -> all MATCH",
            y.snapshot.recheck()["disk_matches_snapshot"] is True)

    # ---- the real frozen manifest (JSON only; CSVs not opened) -------
    real_m = os.path.join(APP, "manifest", "source_manifest.json")
    if os.path.isfile(real_m):
        T.check("M01", "W/manifest/source_manifest.json sha == "
                "PINNED_MANIFEST_SHA256 (frozen in code, from v0.5/review)",
                sha(real_m) == SA.PINNED_MANIFEST_SHA256, sha(real_m))
        pins, msha, _ = PS.load_manifest(real_m, NAMES,
                                         SA.PINNED_MANIFEST_SHA256)
        T.check("M14", "frozen manifest lists exactly the six files with "
                "sha256 + bytes", sorted(pins) == sorted(NAMES))
    else:
        T.skip("M01", "frozen manifest check", "manifest not present")
    shutil.rmtree(FIX)
    T.check("Z01", "synthetic fixtures removed", not os.path.isdir(FIX))
    return T.save()


if __name__ == "__main__":
    raise SystemExit(main())
