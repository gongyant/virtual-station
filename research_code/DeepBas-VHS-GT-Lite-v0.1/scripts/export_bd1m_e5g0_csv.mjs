import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const runtimeRequire = createRequire('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const { Workbook } = await import(pathToFileURL(runtimeRequire.resolve('@oai/artifact-tool')).href);
const root = process.cwd();
const rows = JSON.parse(await fs.readFile(path.join(root,'reports/literature/e5g0_sources/matrix_rows.json'),'utf8'));
const columns = Object.keys(rows[0]);
const values = [columns,...rows.map(row=>columns.map(key=>String(row[key])))];
const book = Workbook.create();
const sheet = book.worksheets.add('Evidence');
const range = sheet.getRange(`A1:T${values.length}`);
range.values = values;
const out = range.values;
if (JSON.stringify(out)!==JSON.stringify(values)) throw new Error('Spreadsheet value round-trip mismatch');
const csvCell = value => '"'+String(value).replaceAll('"','""')+'"';
await fs.writeFile(path.join(root,'outputs/vhs_bd1m/paper/e5g0_literature_evidence_matrix.csv'),'\ufeff'+out.map(row=>row.map(csvCell).join(',')).join('\r\n')+'\r\n','utf8');
console.log(`literature_csv_rows=${rows.length}; columns=${columns.length}; round_trip=PASS`);
